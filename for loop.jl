#for loop

for i=1:10# 1 is starting point abd 10 is ending point
        println(i)
    i=i+1
end

for i=1:10:50# 1 is starting point abd 10 is jumping value and 50 is ending point
    println(i)
    i=i+1
end

for i=10:-1:1# 10 is starting point abd -1 is jumping value and 10 is ending point
    println(i)
    i=i+1
end